let tournamentFinanceSelection = '';
let tournamentFinanceYear = null;
let tournamentFinanceReturn = 'screen-calendar';
let tournamentFinanceReturnModal = '';
let tournamentFinanceResultsEvent = null;

function trTournamentFinance(key, values = {}) {
    const lang = typeof currentLang === 'string' ? currentLang : 'pl';
    return (TOURNAMENT_FINANCE_TRANSLATIONS[lang]?.[key] || TOURNAMENT_FINANCE_TRANSLATIONS.pl[key] || key)
        .replace(/\{(\w+)\}/g, (_, name) => values[name] ?? `{${name}}`);
}

function tournamentFinanceMoney(amount) {
    return amount === null || !Number.isFinite(amount) ? '—' : `${amount < 0 ? '−' : ''}£${Math.abs(amount).toLocaleString('en-GB')}`;
}

function getTournamentFinanceEvents() {
    const events = new Map();
    Object.values(player?.tournamentFinances?.entries || {}).forEach(entry => events.set(getTournamentFinanceKey(entry, 0), entry));
    (typeof tournamentDatabase !== 'undefined' ? tournamentDatabase : []).forEach(event => events.set(getTournamentFinanceKey(event, 0), event));
    return [...events.values()].sort((a, b) => getTournamentDisplayName(a).localeCompare(getTournamentDisplayName(b), getPlayerProfileLocale()));
}

function renderTournamentPrizeTable(event) {
    const preview = getTournamentPrizePreview(event), h = escapeHtml, tr = trTournamentFinance;
    if (!preview) return '';
    if (preview.qualifier) return `<p class="finance-notice">${h(tr('noPrize'))}</p>`;
    const stageLabel = row => {
        if (row.position) return tr('position', { place: row.position });
        if (['groupExit', 'groupSecond', 'groupThird'].includes(row.stage)) return tr(row.stage);
        if (row.stage) {
            const rounds = { winner: 2, runnerUp: 2, semiFinal: 4, quarterFinal: 8, last16: 16 };
            return getSeasonResultStage(rounds[row.stage], row.stage === 'winner');
        }
        return getSeasonResultStage(row.round, row.won);
    };
    return `<p class="finance-ranking">${preview.rankings.length ? `${h(tr('ranking'))} <strong>${preview.rankings.map(key => h(tr(key))).join(' · ')}</strong>` : h(tr('nonRanking'))}</p>
        <div class="finance-table-wrap"><table class="finance-table"><thead><tr><th scope="col">${h(tr('result'))}</th><th scope="col">${h(tr('amount'))}</th>${preview.team ? `<th scope="col">${h(tr('teamAmount'))}</th>` : ''}</tr></thead>
        <tbody>${preview.rows.map(row => `<tr class="${row.won || row.stage === 'winner' ? 'finance-winner' : ''}"><th scope="row">${h(stageLabel(row))}</th><td>${h(tournamentFinanceMoney(row.amount))}</td>${preview.team ? `<td>${h(tournamentFinanceMoney(row.teamAmount))}</td>` : ''}</tr>`).join('')}</tbody></table></div>
        <p class="finance-note">${h(tr('prizeNote'))}</p>${preview.team || preview.slam || preview.playoffs ? `<p class="finance-note">${h(tr(preview.team ? 'teamNote' : preview.slam ? 'slamNote' : 'placementNote'))}</p>` : ''}`;
}

function renderTournamentFinanceSummary(event, year = getCurrentSeasonYear()) {
    const entry = getTournamentFinanceEntry(event, year), h = escapeHtml, tr = trTournamentFinance;
    if (!entry) return `<p class="finance-note">${h(tr('noRecord'))}</p>`;
    const net = getTournamentNetCash(entry);
    const settled = entry.settledAt || (event.completed && Number(year) === getCurrentSeasonYear());
    const row = (key, value) => `<div><dt>${h(tr(key))}</dt><dd>${h(tournamentFinanceMoney(value))}</dd></div>`;
    return `<section class="finance-statement"><h3>${h(tr('summary'))} · ${year}</h3>
        <p class="finance-note">${h(tr(settled ? 'settled' : 'ongoing'))}</p><dl>
        ${row('prize', entry.prize)}${row('sponsorBonus', entry.sponsorBonus)}${row('bonuses', entry.bonuses)}${row('travel', entry.travel === null ? null : -entry.travel)}
        <div class="finance-net ${net < 0 ? 'finance-negative' : ''}"><dt>${h(tr(entry.partial ? 'knownNet' : 'net'))}</dt><dd>${h(tournamentFinanceMoney(net))}</dd></div></dl>
        ${entry.partial ? `<p class="finance-notice">${h(tr('partial'))}</p>` : ''}
        <p class="finance-note">${h(tr('sponsorNote'))}</p><p class="finance-note">${h(tr('scope'))}</p></section>`;
}

function showTournamentFinance(index) {
    initializeTournamentFinances();
    const previous = document.querySelector('.screen.active')?.id;
    if (previous !== 'screen-tournament-finance') {
        tournamentFinanceReturn = previous || 'screen-calendar';
        tournamentFinanceReturnModal = ['results-modal', 'bracket-modal'].find(id => document.getElementById(id)?.style.display === 'flex') || '';
        if (tournamentFinanceReturnModal) document.getElementById(tournamentFinanceReturnModal).style.display = 'none';
    }
    const requested = Number.isInteger(index) ? tournamentDatabase[index]
        : (typeof activeTournament !== 'undefined' ? activeTournament : null);
    if (requested) {
        tournamentFinanceSelection = getTournamentFinanceKey(requested, 0);
        tournamentFinanceYear = getCurrentSeasonYear();
    }
    renderTournamentFinance();
    showScreen('screen-tournament-finance');
}

function renderTournamentFinance() {
    const events = getTournamentFinanceEvents(), h = escapeHtml, tr = trTournamentFinance;
    const event = events.find(candidate => getTournamentFinanceKey(candidate, 0) === tournamentFinanceSelection) || events[0];
    if (!event) {
        document.getElementById('tournament-finance-content').innerHTML = `<h2>${h(tr('title'))}</h2><p class="finance-note">${h(tr('noRecord'))}</p>`;
        document.getElementById('finance-back').textContent = tr('back');
        return;
    }
    tournamentFinanceSelection = getTournamentFinanceKey(event, 0);
    const years = [...new Set([getCurrentSeasonYear(), ...Object.values(player.tournamentFinances.entries)
        .filter(entry => getTournamentFinanceKey(entry, 0) === tournamentFinanceSelection).map(entry => entry.year)])].sort((a, b) => b - a);
    if (!years.includes(tournamentFinanceYear)) tournamentFinanceYear = years[0];
    document.getElementById('tournament-finance-content').innerHTML = `<h2>${h(tr('title'))}</h2>
        <label class="finance-label" for="finance-tournament">${h(tr('tournament'))}</label>
        <select id="finance-tournament" class="finance-select" onchange="tournamentFinanceSelection=this.value; tournamentFinanceYear=null; renderTournamentFinance()">
        ${events.map(candidate => { const key = getTournamentFinanceKey(candidate, 0); return `<option value="${h(key)}" ${key === tournamentFinanceSelection ? 'selected' : ''}>${h(getTournamentDisplayName(candidate))}</option>`; }).join('')}</select>
        <h3>${h(tr('prizes'))}</h3>${renderTournamentPrizeTable(event)}
        <label class="finance-label" for="finance-year">${h(tr('year'))}</label><select id="finance-year" class="finance-select finance-year" onchange="tournamentFinanceYear=Number(this.value); renderTournamentFinance()">${years.map(year => `<option value="${year}" ${year === tournamentFinanceYear ? 'selected' : ''}>${year}</option>`).join('')}</select>
        ${renderTournamentFinanceSummary(event, tournamentFinanceYear)}`;
    document.getElementById('finance-back').textContent = tr('back');
}

function closeTournamentFinance() {
    showScreen(tournamentFinanceReturn);
    if (tournamentFinanceReturnModal) document.getElementById(tournamentFinanceReturnModal).style.display = 'flex';
}

function updateTournamentFinanceResults(event) {
    const container = document.getElementById('tournament-finance-results');
    if (!container) return;
    tournamentFinanceResultsEvent = event || null;
    const entry = event && getTournamentFinanceEntry(event);
    container.hidden = !entry;
    container.innerHTML = entry ? renderTournamentFinanceSummary(event) : '';
}

function showTournamentFinanceCompletion(event) {
    if (event && getTournamentFinanceEntry(event) && typeof showCompletedTournamentResults === 'function') showCompletedTournamentResults(event);
}

function refreshTournamentFinanceTranslations() {
    ['finance-calendar-link', 'finance-active-link'].forEach(id => {
        const element = document.getElementById(id);
        if (element) element.textContent = trTournamentFinance('link');
    });
    if (document.getElementById('screen-tournament-finance')?.classList.contains('active')) renderTournamentFinance();
    if (tournamentFinanceResultsEvent) updateTournamentFinanceResults(tournamentFinanceResultsEvent);
}
