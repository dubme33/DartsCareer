const AI_DART_EDITOR_GROUPS = [
    { title: 'barrel', fields: ['barrelShape', 'barrelPattern', 'barrelLength', 'weightGrams',
        'barrelColor', 'barrelAccentColor', 'barrelAccentStyle', 'front', 'middle', 'rear'] },
    { title: 'point', fields: ['tipLength', 'tipStyle', 'tipColor'] },
    { title: 'shaft', fields: ['flightSystem', 'shaftLength', 'shaftStyle', 'shaftColor', 'integratedColor'] },
    { title: 'flights', fields: ['flightShape', 'flightPattern', 'flightColor', 'flightAccentColor'] }
];
const AI_DART_COLOR_FIELDS = new Set(['barrelColor', 'barrelAccentColor', 'shaftColor', 'integratedColor',
    'tipColor', 'flightColor', 'flightAccentColor']);
let aiDartEditorPending = null;
let aiDartEditorChanged = false;
let aiDartEditorReset = false;
let aiDartEditorGeneration = 0;

function trAiDartEditor(key) {
    const lang = typeof currentLang === 'string' && AI_DART_EDITOR_TEXT[currentLang] ? currentLang : 'pl';
    return AI_DART_EDITOR_TEXT[lang][key] || AI_DART_EDITOR_TEXT.pl[key] || key;
}
function aiDartEditorEscape(value) {
    return String(value ?? '').replace(/[&<>"']/g, char => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[char]);
}
function getAiDartEditorCandidate(candidate = playerEditorCreating ? null : getPlayerEditorCandidate()) {
    return candidate || { id: 'new-ai-player', name: 'New AI Player', country: 'Polska' };
}
function getAiDartAppearanceForPlayer(candidate) {
    if (candidate?.aiDartAppearance) return normalizeAiDartAppearance(candidate.aiDartAppearance);
    return normalizeAiDartAppearance(getDartLoadoutForPlayer(candidate));
}
function setAiDartEditorStatus(message = '', error = false) {
    const element = document.getElementById('ai-dart-editor-status');
    if (!element) return;
    element.textContent = message;
    element.classList.toggle('is-error', error);
}
function aiDartFieldValue(field) {
    if (['front', 'middle', 'rear'].includes(field)) return aiDartEditorPending.gripZones[field];
    return aiDartEditorPending[field];
}
function aiDartEditorControl(field) {
    const label = aiDartEditorEscape(trAiDartEditor(field));
    const value = aiDartFieldValue(field);
    if (AI_DART_COLOR_FIELDS.has(field)) return `<label data-ai-dart-field="${field}"><span>${label}</span>
        <input type="color" value="${value}" onchange="changeAiDartSetting('${field}',this.value)"></label>`;
    if (field === 'weightGrams' || field === 'barrelLength') {
        const min = field === 'weightGrams' ? 12 : 35, max = field === 'weightGrams' ? 40 : 55;
        const unit = field === 'weightGrams' ? 'g' : 'mm';
        return `<label data-ai-dart-field="${field}"><span>${label}: <output>${value} ${unit}</output></span>
            <input type="range" min="${min}" max="${max}" step="1" value="${value}"
                oninput="this.parentNode.querySelector('output').textContent=this.value+' ${unit}'"
                onchange="changeAiDartSetting('${field}',this.value)"></label>`;
    }
    const category = ['front', 'middle', 'rear'].includes(field) ? 'barrelPattern' : field;
    const items = dartCustomizationCatalogue[category];
    const langIndex = { pl: 0, en: 1, de: 2, nl: 3 }[typeof currentLang === 'string' ? currentLang : 'pl'] ?? 0;
    return `<label data-ai-dart-field="${field}"><span>${label}</span><select onchange="changeAiDartSetting('${field}',this.value)">
        ${items.map(item => `<option value="${item.id}" ${String(value) === item.id ? 'selected' : ''}>${aiDartEditorEscape(item.names[langIndex] || item.names[0])}</option>`).join('')}
        </select></label>`;
}
function renderAiDartEditorControls() {
    const host = document.getElementById('ai-dart-editor-controls');
    if (!host || !aiDartEditorPending) return;
    host.innerHTML = AI_DART_EDITOR_GROUPS.map(group => `<div class="ai-dart-control-group">
        <h5>${aiDartEditorEscape(trAiDartEditor(group.title))}</h5><div class="ai-dart-control-grid">
        ${group.fields.map(aiDartEditorControl).join('')}</div></div>`).join('');
    const integrated = aiDartEditorPending.flightSystem !== 'separate';
    for (const field of ['shaftStyle', 'shaftColor', 'integratedColor']) {
        const label = host.querySelector(`[data-ai-dart-field="${field}"]`);
        if (label) label.classList.toggle('is-hidden', field === 'integratedColor' ? !integrated : integrated);
    }
}
function refreshAiDartEditorPreview() {
    if (!aiDartEditorPending) return;
    const host = document.getElementById('ai-dart-editor-preview');
    if (!host) return;
    const appearance = dartModel.normalize(aiDartEditorPending);
    host.innerHTML = typeof dartCustomizationPreviewMarkup === 'function'
        ? dartCustomizationPreviewMarkup(appearance) : '';
    const measurements = document.getElementById('ai-dart-editor-measurements');
    if (measurements) measurements.textContent = `${appearance.tipLength} mm · ${appearance.barrelLength} mm · ${appearance.shaftLength} mm · ${appearance.weightGrams} g`;
    document.getElementById('ai-dart-editor-artwork-remove').disabled = !aiDartEditorPending.flightArtwork;
    if (typeof dartPreview !== 'undefined' && host.getClientRects().length)
        dartPreview.mount(host, appearance, trAiDartEditor('preview'));
}
function populateAiDartEditor(candidate) {
    const section = document.getElementById('player-editor-darts');
    if (!section || typeof normalizeAiDartAppearance !== 'function') return;
    aiDartEditorGeneration++;
    const career = candidate && typeof player !== 'undefined' && (candidate === player
        || Boolean(candidate.id && player?.id && candidate.id === player.id));
    section.hidden = !!career;
    if (career) { aiDartEditorPending = null; return; }
    aiDartEditorPending = getAiDartAppearanceForPlayer(getAiDartEditorCandidate(candidate));
    aiDartEditorChanged = false;
    aiDartEditorReset = false;
    setAiDartEditorStatus();
    renderAiDartEditorControls();
    refreshAiDartEditorPreview();
}
function changeAiDartSetting(field, value) {
    if (!aiDartEditorPending || !(AI_DART_COLOR_FIELDS.has(field) || AI_DART_EDITOR_GROUPS.some(group => group.fields.includes(field)))) return false;
    if (['front', 'middle', 'rear'].includes(field)) aiDartEditorPending.gripZones[field] = value;
    else {
        aiDartEditorPending[field] = value;
        if (field === 'barrelPattern') aiDartEditorPending.gripZones = { front: value, middle: value, rear: value };
    }
    aiDartEditorPending = normalizeAiDartAppearance(aiDartEditorPending);
    aiDartEditorChanged = true;
    aiDartEditorReset = false;
    renderAiDartEditorControls();
    refreshAiDartEditorPreview();
    setAiDartEditorStatus(trAiDartEditor('editReady'));
    return true;
}
function resetAiDartAppearance() {
    const candidate = getAiDartEditorCandidate();
    aiDartEditorPending = normalizeAiDartAppearance(getDartLoadoutForPlayer({ ...candidate, aiDartAppearance: null }));
    aiDartEditorChanged = true;
    aiDartEditorReset = true;
    renderAiDartEditorControls();
    refreshAiDartEditorPreview();
    setAiDartEditorStatus(trAiDartEditor('resetReady'));
}
async function uploadAiDartArtwork(event) {
    const input = event?.target;
    const file = input?.files?.[0];
    if (input) input.value = '';
    if (!file || !aiDartEditorPending) return false;
    if (!['image/png', 'image/jpeg', 'image/webp'].includes(file.type) || file.size > 5 * 1024 * 1024) {
        setAiDartEditorStatus(trAiDartEditor('artworkError'), true); return false;
    }
    const generation = aiDartEditorGeneration;
    let url;
    try {
        url = URL.createObjectURL(file);
        const image = await new Promise((resolve, reject) => {
            const loaded = new Image();
            loaded.onload = () => resolve(loaded);
            loaded.onerror = reject;
            loaded.src = url;
        });
        if (generation !== aiDartEditorGeneration) return false;
        if (!image.naturalWidth || !image.naturalHeight || image.naturalWidth > 8192 || image.naturalHeight > 8192)
            throw new Error('Invalid artwork dimensions');
        const canvas = document.createElement('canvas'); canvas.width = canvas.height = 256;
        const side = Math.min(image.naturalWidth, image.naturalHeight);
        canvas.getContext('2d').drawImage(image, (image.naturalWidth - side) / 2,
            (image.naturalHeight - side) / 2, side, side, 0, 0, 256, 256);
        const artwork = canvas.toDataURL('image/png');
        if (!dartModel.validFlightArtwork(artwork)) throw new Error('Artwork exceeds save limit');
        dartModel.registerFlightArtwork(artwork, canvas);
        aiDartEditorPending.flightArtwork = artwork;
        aiDartEditorChanged = true;
        aiDartEditorReset = false;
        refreshAiDartEditorPreview();
        setAiDartEditorStatus(trAiDartEditor('artworkReady'));
        return true;
    } catch (_) {
        if (generation === aiDartEditorGeneration) setAiDartEditorStatus(trAiDartEditor('artworkError'), true);
        return false;
    } finally { if (url) URL.revokeObjectURL(url); }
}
function removeAiDartArtwork() {
    if (!aiDartEditorPending?.flightArtwork) return false;
    aiDartEditorPending.flightArtwork = null;
    aiDartEditorChanged = true;
    aiDartEditorReset = false;
    refreshAiDartEditorPreview();
    setAiDartEditorStatus(trAiDartEditor('editReady'));
    return true;
}
function applyAiDartEditorToCandidate(candidate) {
    if (!candidate || !aiDartEditorChanged) return false;
    if (aiDartEditorReset) delete candidate.aiDartAppearance;
    else candidate.aiDartAppearance = normalizeAiDartAppearance(aiDartEditorPending);
    return true;
}
function refreshAiDartEditorTranslations() {
    if (typeof document === 'undefined' || !document.getElementById('ai-dart-editor-title')) return;
    const ids = { 'ai-dart-editor-title': 'title', 'ai-dart-editor-hint': 'hint',
        'ai-dart-editor-artwork-label': 'artwork', 'ai-dart-editor-artwork-remove': 'removeArtwork',
        'ai-dart-editor-reset': 'reset', 'ai-dart-editor-reset-view': 'resetView' };
    for (const [id, key] of Object.entries(ids)) document.getElementById(id).textContent = trAiDartEditor(key);
    if (aiDartEditorPending) { renderAiDartEditorControls(); refreshAiDartEditorPreview(); }
}
if (typeof document !== 'undefined') refreshAiDartEditorTranslations();
