function applyKnownPlayerBirthYears(players) {
    if (!Array.isArray(players)) return;

    players.forEach(candidate => {
        if (!candidate || candidate.isBye) return;
        if (!Object.prototype.hasOwnProperty.call(playerBirthYears, candidate.name)) return;
        if (!Number.isInteger(candidate.birthYear)) {
            candidate.birthYear = playerBirthYears[candidate.name];
        }
    });
}

