function womensAgeCalibrationApplies(candidate) {
    const c = candidate?.womensAgeCalibration;
    return c?.version === 1 && !candidate.isNewgen && !candidate.editorCreated
        && !candidate.playerEditorProfileOverride && candidate.kind !== 'custom'
        && candidate.birthYear === c.birthYear && (candidate.birthDate || null) === c.birthDate;
}

// Historical eligibility/age queries retain the original saved demographics.
// A loaded career finishes its current season before the corrected age takes effect.
function getWomensAgeBirthContext(candidate, referenceDate) {
    if (!womensAgeCalibrationApplies(candidate)) return candidate;
    const date = referenceDate instanceof Date ? referenceDate : new Date(referenceDate);
    const c = candidate.womensAgeCalibration;
    return !c.newCareer && !Number.isNaN(date.getTime()) && date.getFullYear() < c.effectiveYear
        ? {birthYear:c.previousBirthYear, birthDate:c.previousBirthDate, dateOfBirth:null} : candidate;
}

function applyWomensAgeCalibrations(players, referenceDate, {newCareer=false}={}) {
    const date = referenceDate instanceof Date ? referenceDate : new Date(referenceDate);
    if (!Array.isArray(players) || Number.isNaN(date.getTime())) return;
    for (const p of players) {
        if (!p || p.isBye || p.isNewgen || p.editorCreated || p.playerEditorProfileOverride || p.kind === 'custom') continue;
        const r = WOMENS_AGE_CALIBRATIONS.find(r => r.id ? p.id === r.id || p.databaseKey === r.id
            : Number.isInteger(p.defaultTemplateIndex) ? p.defaultTemplateIndex === r.defaultTemplateIndex
            : (p.sourceName || p.name) === r.name && p.country === r.country);
        if (!r || p.womensAgeCalibration?.version === 1) continue;
        const original = p.birthYear === r.previousBirthYear && (p.birthDate || p.dateOfBirth || null) === r.previousBirthDate;
        const fresh = newCareer && p.birthYear === r.birthYear && (p.birthDate || null) === r.birthDate;
        // Custom/mod/editor dates are authoritative, even when the ID is a stock ID.
        if (!original && !fresh) continue;
        p.womensAgeCalibration = {version:1, birthYear:r.birthYear, birthDate:r.birthDate,
            previousBirthYear:r.previousBirthYear, previousBirthDate:r.previousBirthDate,
            previousBirthDateSource:newCareer ? r.previousBirthDateSource : p.birthDateSource || null,
            effectiveYear:newCareer ? 2026 : date.getFullYear()+1,
            migratedAt:newCareer ? null : date.getTime(), newCareer, traitsRebased:false};
        p.birthYear = r.birthYear;
        if (r.birthDate) p.birthDate = r.birthDate;
        p.birthDateSource = r.birthDateSource;
        p.birthYearSource = 'confirmed-reference-year';
        // The old legacy RNG identity included Lisa's incorrect birth year.
        // Retain it so correcting age cannot regenerate potential or hidden attributes.
        if (r.foundationIdentity && !p.aiFoundationIdentity) p.aiFoundationIdentity = r.foundationIdentity;
    }
}

