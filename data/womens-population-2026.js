// Versioned starting-rating calibration. Real identities/ranking stay in docs.
function findWomensRatingCalibration(candidate) {
    if (!candidate || candidate.isBye || candidate.isNewgen || candidate.editorCreated || candidate.kind === 'custom') return null;
    return WOMENS_RATING_CALIBRATIONS.find(rule => rule.id
        ? candidate.id === rule.id || candidate.databaseKey === rule.id
        : Number.isInteger(candidate.defaultTemplateIndex)
            ? candidate.defaultTemplateIndex === rule.defaultTemplateIndex
            : (candidate.sourceName || candidate.name) === rule.name && candidate.country === rule.country) || null;
}

function getWomensRatingInitialOverall(candidate, fallback) {
    const calibration = candidate?.womensRatingCalibration;
    if (calibration?.version === 1 && Number.isFinite(calibration.previousStartingOvr)) return calibration.previousStartingOvr;
    return fallback;
}

function getWomensNewgenStartingOverall(previousOverall) {
    return Math.max(45, Math.min(59, Math.round(45 + (previousOverall - 52) * 14 / 22)));
}

function applyWomensRatingCalibrations(players, { newCareer = false, careerPlayer = null, referenceDate = null } = {}) {
    for (const candidate of players || []) {
        const rule = findWomensRatingCalibration(candidate);
        if (!rule || candidate.womensRatingCalibration?.version === 1) continue;
        // Explicit editor ratings always take precedence, including after later loads.
        if (candidate.playerEditorRatingOverride === true || candidate.playerEditorProfileOverride === true) continue;
        const delta = rule.ratings.ovr - rule.previous.ovr;
        const previous = {};
        for (const [field, base, max] of [['ovr','baseOvr',99],['scoring','baseScoring',100],['doubles','baseDoubles',100]]) {
            const current = candidate === careerPlayer
                ? Number(field === 'ovr' ? candidate.overall ?? candidate.ovr : candidate[field] ?? candidate.overall)
                : Number(candidate[base] ?? candidate[field] ?? candidate.ovr);
            if (!Number.isFinite(current)) continue;
            previous[field] = current;
            const value = newCareer ? rule.ratings[field] : Math.max(40, Math.min(max, current + delta));
            if (Number.isFinite(candidate[base])) candidate[base] = newCareer
                ? rule.ratings[field] : Math.max(40, Math.min(max, candidate[base] + delta));
            candidate[field] = candidate === careerPlayer ? value : Math.round(value);
        }
        if (Object.prototype.hasOwnProperty.call(candidate,'overall')) candidate.overall = candidate.ovr;
        // These ratings are operational comparison baselines, not sporting results.
        // Rebase them together so the database correction is not seen as a collapse
        // or a recovery target. Archive original values; retain all earned deltas.
        const previousAiRatings = {};
        if (!newCareer && candidate.aiCareer) {
            const career = candidate.aiCareer;
            if (Number.isFinite(career.historicalPeak?.ovr)) {
                previousAiRatings.peak = {...career.historicalPeak};
                career.historicalPeak.ovr += delta;
            }
            previousAiRatings.history = (career.history || []).map(row => ({year:row.year,ovr:row.ovr}));
            for (const row of career.history || []) if (Number.isFinite(row.ovr)) row.ovr += delta;
        }
        if (!newCareer && candidate.aiDevelopmentSummary) {
            previousAiRatings.summary = {};
            for (const field of ['before','after','seasonStart']) {
                if (!Number.isFinite(candidate.aiDevelopmentSummary[field])) continue;
                previousAiRatings.summary[field] = candidate.aiDevelopmentSummary[field];
                candidate.aiDevelopmentSummary[field] += delta;
            }
        }
        candidate.womensRatingCalibration = {version:1, previousStartingOvr:rule.previous.ovr,
            startingOvr:rule.ratings.ovr, sourceRank:rule.rank, delta, previousRatings:previous,
            migratedAt:newCareer ? null : referenceDate?.getTime?.() || null, newCareer, previousAiRatings};
    }
}

